/**
 * 入力項目の欄に添える一言（R-11 の実測 1）。
 *
 * ## なぜ関数にするか
 *
 * この欄は「**この画面で項目を編集できないとき**」に出る。出る理由は 3 通りあり、
 * **理由ごとに言うことが違う**。`ef9a466` では 1 つの文を固定で出していたので、
 * **新規作成の画面で「ほかでも使われている項目を共有しています」**と言っていた —
 * 共有していないのに、である。
 *
 * 3 通りの分岐を画面の中に書くと試験できないので、ここへ出す。
 */
export function fieldPickerNote(input: {
    isNew: boolean;
    /** この画面で編集する材料が渡っているか（= 束が在るか） */
    hasFieldEditor: boolean;
}): string {
    if (input.isNew) {
        // 作る前は束がまだ無い。作ると自動で付き、この画面で編集できるようになる
        return '入力項目は、保存したあとにこの画面の中で追加できます。';
    }

    if (!input.hasFieldEditor) {
        return '入力項目がまだ決まっていません。上の一覧から選んでください。';
    }

    /*
     * 材料は在るのにこの欄が出ている = ほかでも使われている束である。
     *
     * **行き先を「共有元の画面」と言わない**（B-31）。それはカスタムフィールドの画面で、
     * **利用者に見せないと決めた画面**である。見せない画面へ送るのは案内ではない。
     * この画面の中に出口（切り離し）を置いたので、そちらを指す。
     */
    return 'このフォームは、ほかでも使われている項目を共有しています。このフォームだけで直したいときは、下の「このフォームだけの項目にする」を押してください。';
}
