<?php

declare(strict_types=1);

namespace AgentCms\Core\Wxr\Ledger;

/**
 * 台帳から見た、その 1 件の今（Phase 9.14 / STAGE 27C・SPEC §D.2）。
 *
 * ## 状態であって、決定ではない
 *
 * ここは「台帳に何が書いてあるか」しか言わない。
 * これを取り込みの理由へ落とすのも、対象の行が本当に在るかを確かめるのも、
 * **この先の仕事**である。読むことと決めることを 1 か所に混ぜると、
 * 「読めなかった」と「入れないと決めた」が同じ値で表されるようになる。
 */
enum LedgerState: string
{
    /** 台帳に記録が無い */
    case Absent = 'absent';

    /**
     * 目指している取り込み先に 1 行だけあり、他の取り込み先には無い。
     *
     * このときだけ `target_id` / `batch_id` / 所有権を渡す。
     */
    case Exact = 'exact';

    /**
     * どれを指しているのか決められない。
     *
     * 別の取り込み先に入っている（`--type` を変えて実行し直した）、
     * 両方にある、同じ鍵の行が 2 つある、のいずれかである。
     * **どれであっても「1 行目を採る」はしない** — 採った方が正しい保証が無い。
     */
    case Conflict = 'conflict';
}
