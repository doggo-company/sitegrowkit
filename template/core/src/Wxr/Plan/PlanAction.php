<?php

declare(strict_types=1);

namespace AgentCms\Core\Wxr\Plan;

/**
 * 1 件について `apply` が何をするか（Phase 9.14 / STAGE 27C・SPEC §D.2）。
 *
 * ## V1 は「既にあるものへ書かない」
 *
 * SPEC §D.2 は「既にある行は更新か飛ばす」と両案を残していた。**飛ばす方を採る。**
 *
 * 台帳（`import_records`）は、その行を**取り込みの後に人が直したかどうか**を
 * 見分ける材料を持っていない（取り込み時点の中身の hash も、対象側の版も無い）。
 * 見分けられないまま更新すると、**移行後に人が手を入れた記事を黙って上書きする**。
 * 上書きされた側は、何が消えたのかを知る手段が無い。
 *
 * 飛ばす側の損は「変更が反映されない」だけで、しかもそれは件数として報告される。
 * 途中で落ちた取り込みの再実行も、既にあるものを飛ばして**作れていない分だけ作る**
 * 形で成立する（§D.5）。
 *
 * 差分更新は、取り込み元の中身の hash と人の編集を守る仕組みを設計してからの別の話である。
 */
enum PlanAction: string
{
    /** こちらにまだ無いので作る */
    case Create = 'create';

    /** 台帳に記録があるので触らない（件数と理由を報告する） */
    case SkipExisting = 'skip_existing';

    /**
     * 受け皿が既にあるので、作らずにそれを使う（分類の項目 — §C.3）。
     *
     * **`create` とも `skip_existing` とも別に数える。**
     * `create` に混ぜると作った件数が水増しされ、`skip_existing` に混ぜると
     * 「台帳にあるから触らない」と区別がつかなくなる。
     * そして**取り消しのときに何を消してよいかが変わる** —
     * こちらが作った項目は消してよいが、元からあった項目は消してはならない。
     */
    case Reuse = 'reuse';

    /**
     * 台帳に記録があるのに対象が見つからない、型が食い違う。
     *
     * **決められないので plan を止める。** 勝手に作り直すと、
     * 消したはずのものが戻る。無視すると、台帳が現実と合わないまま増える。
     */
    case Conflict = 'conflict';
}
