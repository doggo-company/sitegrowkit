<?php

declare(strict_types=1);

namespace AgentCms\Core\ContentTypes;

use AgentCms\Core\Ordering\SortOrderColumn;
use AgentCms\Core\Trash\TrashColumns;
use AgentCms\Core\Wxr\Status\WxrStatusColumn;
use JsonException;

/**
 * 検証済み下書き → 生成ファイルの中身（Phase 9.4 / STAGE #17A）。
 *
 * **決定的**である。同じ下書きからは常に同じ文字列が出る
 * （migration のタイムスタンプだけが呼び出し側から渡される）。
 *
 * ## 注入対策
 *
 * PHP ソースへ埋め込むのは `ContentTypeIdentifier` と `FieldDraft` が
 * 検証済みの identifier（`[a-z][a-z0-9_]{1,39}`）と整数だけである。
 * **label / help / choices といった自由入力は PHP にも SQL にも入らない** —
 * 行き先は `json_encode` を通る Schema JSON だけなので、
 * ブロックコメント終端による脱出も、クォート脱出も成立しない。
 */
final class ContentTypeGenerator
{
    /** 生成物であることを機械可読に示す印（再生成・検出に使う） */
    public const MARKER = 'generated by agentcms content type builder';

    /** @throws JsonException */
    public function schemaJson(ContentTypeDraft $draft): string
    {
        return json_encode(
            $draft->toSchemaArray(),
            JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR,
        )."\n";
    }

    public function modelSource(ContentTypeDraft $draft): string
    {
        $id = $draft->identifier;
        $class = $id->studly();
        $marker = self::MARKER;

        return <<<PHP
        <?php

        declare(strict_types=1);

        namespace Modules\\{$class}\\Models;

        use AgentCms\\Core\\Content\\HasContentSchema;
        use AgentCms\\Core\\Content\\SchemaModel;
        use Illuminate\\Database\\Eloquent\\Model;

        /*
         * {$marker} — Phase 9.4。
         *
         * 項目定義の単一情報源は content/schemas/{$id->value}.json。
         * このクラスは schema id とテーブルを結ぶだけで、独自の業務ロジックを持たない
         * （fillable / casts は HasContentSchema が schema から導出する）。
         */
        final class {$class} extends Model implements SchemaModel
        {
            use HasContentSchema;

            protected \$table = '{$id->table()}';

            public static function schemaId(): string
            {
                return '{$id->value}';
            }
        }

        PHP;
    }

    public function migrationSource(ContentTypeDraft $draft): string
    {
        $id = $draft->identifier;
        $table = $id->table();
        $marker = self::MARKER;

        $columns = [];
        $foreignKeys = [];

        foreach ($draft->fields as $field) {
            $columns[] = '            $table->'.$field->type->columnExpression($field).';';

            $foreign = $field->type->foreignKeyExpression($field);

            if ($foreign !== null) {
                $foreignKeys[] = '            $table->'.$foreign.';';
            }
        }

        /*
         * `data` JSON は **常に持たせる**（Phase 9.5-B / owner 決定 G2-(a)）。
         *
         * Builder が選べる 16 型はすべて column-backed なので、作った直後は空のままだが、
         * Field Group を割り当てた瞬間に受け皿が要る。無いと投稿の保存が壊れる。
         * 後から ALTER するより、最初から nullable で置いておくほうが安全である。
         */
        $columns[] = '            $table->json(\'data\')->nullable();';

        /*
         * ゴミ箱の列（Phase 9.8 / STAGE 21B・OG1 = (b)）。
         *
         * **最初から持たせる。** 後から追随の migration を当てる形にすると、
         * 作った直後の型だけゴミ箱が使えない期間ができる。形を書くのは
         * `TrashColumns` 1 か所なので、既存の型と同じ形に必ず揃う。
         */
        $columns[] = '            $table->timestamp(\''.TrashColumns::DELETED_AT.'\')->nullable()->index();';
        $columns[] = '            $table->unsignedBigInteger(\''.TrashColumns::TRASHED_BY.'\')->nullable();';
        $columns[] = '            $table->unsignedBigInteger(\''.TrashColumns::LOCK_VERSION.'\')->default(0);';

        /*
         * 取り込み元の公開状態（Phase 9.14 / SPEC §C.8.3）。
         * **新しく作る型にも最初から持たせる。** 後から migration で追いかける形だと、
         * 追いかける前に取り込みが走った型だけ出自が残らない。
         */
        $columns[] = '            $table->string(\''.WxrStatusColumn::NAME.'\', '.WxrStatusColumn::LENGTH.')->nullable();';

        /*
         * 掲載順（P1 ②）。**新しく作る型にも最初から持たせる。**
         * 後から追随する形だと、追いつく前は「型によって並べ替えられない」が生まれる。
         */
        $columns[] = '            $table->unsignedInteger(\''.SortOrderColumn::NAME.'\')->default(0)->index();';

        $body = implode("\n", $columns);
        $constraints = $foreignKeys === [] ? '' : "\n\n".implode("\n", $foreignKeys);

        return <<<PHP
        <?php

        declare(strict_types=1);

        use Illuminate\\Database\\Migrations\\Migration;
        use Illuminate\\Database\\Schema\\Blueprint;
        use Illuminate\\Support\\Facades\\Schema;

        /*
         * {$marker} — Phase 9.4。
         *
         * カラムは content/schemas/{$id->value}.json の column-backed フィールドと一致する
         * （SchemaTableParityTest が検証する）。手で編集しないこと。
         */
        return new class extends Migration
        {
            public function up(): void
            {
                Schema::create('{$table}', function (Blueprint \$table): void {
                    \$table->id();
        {$body}
                    \$table->timestamps();{$constraints}
                });
            }

            public function down(): void
            {
                Schema::dropIfExists('{$table}');
            }
        };

        PHP;
    }
}
