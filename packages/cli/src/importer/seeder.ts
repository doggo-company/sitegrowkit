import type { TemplatePlan } from "./plan-types.js";
import { cardsOf, datedOf } from "./seeds.js";

/**
 * Static Template と同等の見た目を再現する fixture データの Seeder を生成する（spec §32）。
 * - 冪等（updateOrCreate / firstWhere）
 * - Media はカード画像を Media Entity として取り込み Works に添付する
 * - 既存 DatabaseSeeder は変更しない（--class 指定で明示実行）
 */
export function generateSeeder(plan: TemplatePlan): string {
  const siteRows = Object.entries(plan.seeds.site)
    .map(([k, v]) => `            '${php(k)}' => '${php(v)}',`)
    .join("\n");
  /*
   * 投入先は plan が持つ（R-13 Stage 2）。**型名を名指ししない。**
   * CMS が作った型は `Modules\\Works\\Models\\Works`、kit の例は `…\\Work` と
   * クラス名の規則が違うので、`model` をそのまま使って別名で取り込む。
   */
  const cards = cardsOf(plan);
  const dated = datedOf(plan);
  const cardModel = cards?.model ?? null;
  const datedModel = dated?.model ?? null;
  const worksRows = (cards?.rows ?? [])
    .map((w) => {
      const image = w.image ? `'${basename(w.image)}'` : "null";
      const excerpt = w.excerpt ?? w.title;
      return `            ['title' => '${php(w.title)}', 'slug' => '${php(w.slug)}', 'category' => '${php(w.category)}', 'year' => ${w.completed_year}, 'image' => ${image}, 'order' => ${w.order}, 'excerpt' => '${php(excerpt)}'],`;
    })
    .join("\n");
  // excerpt が原文から取れている場合は本文を捏造しない（excerpt をそのまま body に使う）
  const hasRealExcerpt = (cards?.rows ?? []).some(
    (w) => w.excerpt !== undefined && w.excerpt !== null,
  );
  const worksBodyExpr = hasRealExcerpt
    ? "'<p>'.e($row['excerpt']).'</p>'"
    : "'<p>'.e($row['title']).' の制作実績です。</p>'";
  // News: 一覧のみで本文が確定できない場合は body を空にする（存在しない本文を生成しない）
  const hasEmptyNewsBody = (dated?.rows ?? []).some(
    (n) => n.body !== undefined,
  );
  const newsBodyExpr = hasEmptyNewsBody
    ? "$row['body']"
    : "'<p>'.e($row['title']).'</p>'";
  // 全カードに画像がある場合、null 分岐を生成すると PHPStan が常真比較として弾くため条件を出し分ける
  const mediaLine = (cards?.rows ?? []).some((w) => !w.image)
    ? "            $media = $row['image'] !== null ? $this->importMedia($row['image']) : null;"
    : "            $media = $this->importMedia($row['image']);";
  // 原デザインに年が無い（completed_year: null）works は completed_at を捏造しない。
  // PHPStan の常真比較エラーを避けるため、null の分布に応じて分岐を出し分ける
  const years = (cards?.rows ?? []).map((w) => w.completed_year);
  const allYearNull = years.length > 0 && years.every((y) => y === null);
  const someYearNull = years.some((y) => y === null);
  const yearBlock = allYearNull
    ? `            // 原デザインに年の概念が無いため completed_at は設定しない
            $publishedAt = CarbonImmutable::now()->subDay()->subDays($row['order']);
            $completedAt = null;`
    : someYearNull
      ? `            $base = $row['year'] === null ? CarbonImmutable::now()->subDay() : CarbonImmutable::create($row['year'], 12, 31, 12);
            if ($base->isFuture()) {
                $base = CarbonImmutable::now()->subDay();
            }
            $publishedAt = $base->subDays($row['order']);
            $completedAt = $row['year'] === null ? null : $publishedAt->toDateString();`
      : `            $base = CarbonImmutable::create($row['year'], 12, 31, 12);
            if ($base->isFuture()) {
                $base = CarbonImmutable::now()->subDay();
            }
            $publishedAt = $base->subDays($row['order']);
            $completedAt = $publishedAt->toDateString();`;
  const newsRows = (dated?.rows ?? [])
    .map((n) => {
      const body = n.body !== undefined ? `, 'body' => '${php(n.body)}'` : "";
      return `            ['title' => '${php(n.title)}', 'slug' => '${php(n.slug)}', 'date' => '${php(n.date)}', 'order' => ${n.order}${body}],`;
    })
    .join("\n");
  const mediaMeta = plan.assets.media
    .map(
      (m) =>
        `            '${php(basename(m.from))}' => ['name' => '${php(m.name)}', 'alt' => '${php(m.alt)}'],`,
    )
    .join("\n");

  return `<?php

namespace Database\\Seeders;

use AgentCms\\Core\\Settings\\SettingsStore;
use Carbon\\CarbonImmutable;
use Illuminate\\Database\\Console\\Seeds\\WithoutModelEvents;
use Illuminate\\Database\\Seeder;
use Illuminate\\Support\\Facades\\Storage;
use Modules\\Media\\Models\\Media;${cardModel === null ? "" : `\nuse ${cardModel} as CardModel;`}${datedModel === null ? "" : `\nuse ${datedModel} as DatedModel;`}

/**
 * generated by agentcms template apply — テンプレート import の fixture parity データ。
 * Static Template のカード / ニュースと同一の内容を CMS 側へ投入する（visual regression 用）。
 * 実行: php artisan db:seed --class=Database\\\\Seeders\\\\TemplateContentSeeder
 */
class TemplateContentSeeder extends Seeder
{
    use WithoutModelEvents;

    public function run(): void
    {
        // Site Settings 初期値（テンプレートの og:site_name / description 由来）。
        // ユーザーが設定済みの値は上書きしない
        $settings = app(SettingsStore::class);
        $site = [
${siteRows}
        ];
        foreach ($site as $key => $value) {
            if (blank($settings->get($key))) {
                $settings->put([$key => $value]);
            }
        }

        $works = [
${worksRows}
        ];
        foreach ($works as $row) {
${mediaLine}
            // published_at は「年末（未来なら現在時刻へクランプ）- order 日」:
            // published() スコープ（未来日付を除外）に掛からず、一覧の並び（published_at desc）が
            // テンプレートのカード順と一致する。表示は年のみなので completed_at の年は保たれる
${yearBlock}
            CardModel::query()->updateOrCreate(['slug' => $row['slug']], [
                'title' => $row['title'],
                'category' => $row['category'],
                'excerpt' => $row['excerpt'],
                'body' => ${worksBodyExpr},
                'completed_at' => $completedAt,
                'status' => 'published',
                'published_at' => $publishedAt,
                'main_image_id' => $media?->id,
            ]);
        }

        $news = [
${newsRows}
        ];
        foreach ($news as $row) {
            DatedModel::query()->updateOrCreate(['slug' => $row['slug']], [
                'title' => $row['title'],
                'body' => ${newsBodyExpr},
                'status' => 'published',
                'published_at' => CarbonImmutable::parse($row['date'])->setTime(12, 0),
            ]);
        }
    }

    /**
     * database/seeders/template-import/ の画像を Media として取り込む（冪等）。
     * unit テスト時はスキップ（実ストレージを汚さない — DemoContentSeeder と同方針）。
     */
    private function importMedia(string $filename): ?Media
    {
        if (app()->runningUnitTests()) {
            return null;
        }

        $meta = [
${mediaMeta}
        ];
        $name = $meta[$filename]['name'] ?? $filename;
        $alt = $meta[$filename]['alt'] ?? '';

        $existing = Media::query()->firstWhere('name', $name);
        if ($existing !== null) {
            return $existing;
        }

        $sourcePath = database_path('seeders/template-import/'.$filename);
        if (! is_file($sourcePath)) {
            return null;
        }

        $disk = Storage::disk((string) config('agentcms.uploads.disk'));
        $storedPath = 'media/imported-'.$filename;
        $disk->put($storedPath, (string) file_get_contents($sourcePath));
        $dimensions = getimagesize($sourcePath);

        return Media::query()->create([
            'name' => $name,
            'alt' => $alt,
            'path' => $storedPath,
            'mime' => $dimensions !== false ? (string) $dimensions['mime'] : 'image/png',
            'size' => (int) $disk->size($storedPath),
            'width' => $dimensions !== false ? (int) $dimensions[0] : 0,
            'height' => $dimensions !== false ? (int) $dimensions[1] : 0,
            'has_webp' => false,
        ]);
    }
}
`;
}

function php(v: string): string {
  return v.replaceAll("\\", "\\\\").replaceAll("'", "\\'");
}

function basename(path: string): string {
  return path.split("/").pop() ?? path;
}
