import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";

import { hashContent } from "./apply.js";

/**
 * kit が同梱している「別案件の生成物」を見分ける（B-60）。
 *
 * ## なぜ要るのか
 *
 * 🔴 **生成したばかりの案件で `template apply` を打つと conflict が出る**
 * （2026-08-28 実測・2 件）。kit の `template/` に**別案件の生成物**が入っていて、
 * apply から見れば「記録に無い既存ファイル」= `foreign` になるためである。
 *
 * **利用者は初回から `--force` を打つことになる。**
 *
 * 🔴 **これは道具の問題ではなく、人の習慣の問題である。**
 * 一度「初回は `--force` で越えるもの」と覚えたら、
 * **2 回目に出た本物の警告も同じ手で越える。**
 * 実際にそれをやって `/news` を壊した。
 *
 * ## 何を見て決めるのか
 *
 * **2 つとも合ったときだけ**「kit が置いた見本」と判断する。
 *
 * | | 何を見るか | なぜ |
 * | --- | --- | --- |
 * | ① | 先頭の `agentcms:bundled-sample` | **kit が置いたものだけが名乗る**（案件の生成物は名乗らない） |
 * | ② | **中身が同梱時のまま**（ハッシュ一致） | **利用者が手で直していたら飲み込まない** |
 *
 * 🔴 **②が要点である。**①だけだと、**利用者が見本を直してから初回 apply を打った日に、
 * その直しが黙って消える。**害の大きさより「**黙って**」の方が問題で、
 * しかも**製品を初めて触った日に起きる。**
 *
 * ## 飲まなかったときは、何を選ぶのかを言う
 *
 * 手が入っていたら **conflict のまま**にする。ただし
 * **「これは kit の見本です」と言う** — 「conflict です」だけだと、
 * **また `--force` で越える。**
 */
export interface BundledSample {
  /** プロジェクトルート相対 */
  target: string;
  /** 同梱時の中身のハッシュ */
  sha256: string;
}

/**
 * 同梱の見本の一覧を置く場所（案件ルート相対）。
 *
 * **`.agentcms/` の下に置く** — 利用者が触るものではないし、
 * apply が読む唯一の場所だと分かる。
 */
export const BUNDLED_SAMPLES_PATH = ".agentcms/manifest/bundled-samples.json";

/**
 * 同梱の見本の目印（先頭行に入っている）。
 *
 * 🔴 **前は `generated by agentcms template apply` を見ていた（B-61）。**
 * だが同梱の 7 本は**前の案件の生成物ではなく、kit が手で育てている既定**である
 * （生成されたと書いてある日以降に **38 コミットの手直し**が入っている）。
 *
 * **「自動生成だから触るな」と書いてあるのに、実際は手で直され続けていた。**
 * 利用者はその表示を読んで、**触っていいものを触らない。**
 *
 * ▷ **目印と表示は同じ 1 行**である。片方だけ直すと、
 *   **表示を直した瞬間に見本として数えられなくなり、B-60 の conflict が戻る。**
 *   だから**ここを唯一の出どころ**にして、blade 側はこの語を含める。
 */
export const BUNDLED_SAMPLE_MARK = "agentcms:bundled-sample";

/** 同梱物を数える範囲（ここ以外に生成物は置かれない） */
const ROOTS = ["resources/views", "modules"];

/**
 * kit の `template/` を歩いて、同梱されている生成物を集める。
 *
 * **`create` の時点で 1 度だけ数えて、案件へ書き出す**のが正しい使い方である。
 * apply の時点で kit を読みに行くと、**利用者の手元に kit が無い。**
 */
export function collectBundledSamples(templateDir: string): BundledSample[] {
  const out: BundledSample[] = [];

  for (const root of ROOTS) {
    const dir = join(templateDir, root);

    if (!existsSync(dir)) continue;

    walk(dir, templateDir, out);
  }

  return out.sort((a, b) => a.target.localeCompare(b.target));
}

function walk(dir: string, templateDir: string, out: BundledSample[]): void {
  for (const entry of readdirSync(dir)) {
    const abs = join(dir, entry);

    if (statSync(abs).isDirectory()) {
      walk(abs, templateDir, out);

      continue;
    }

    if (!abs.endsWith(".blade.php")) continue;

    const body = readFileSync(abs);

    // 先頭付近に目印が無いものは生成物ではない
    if (!body.subarray(0, 400).toString("utf-8").includes(BUNDLED_SAMPLE_MARK)) {
      continue;
    }

    out.push({
      target: relative(templateDir, abs).split(sep).join("/"),
      sha256: hashContent(body),
    });
  }
}

/**
 * そのファイルが「kit が置いた見本のまま」か。
 *
 * **中身が同梱時と 1 バイトでも違えば false**（＝利用者の手が入っている）。
 */
export function isUntouchedSample(
  samples: BundledSample[],
  target: string,
  current: Buffer,
): boolean {
  const sample = samples.find((s) => s.target === target);

  return sample !== undefined && sample.sha256 === hashContent(current);
}

/**
 * そのファイルが「kit が置いた見本」だったか（中身は問わない）。
 *
 * **conflict の言い方を変えるために使う** — 手が入っていても、
 * **もとは見本だった**ことは伝える価値がある。
 */
export function wasBundledSample(
  samples: BundledSample[],
  target: string,
): boolean {
  return samples.some((s) => s.target === target);
}
