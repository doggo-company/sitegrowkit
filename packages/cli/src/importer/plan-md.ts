import { matchLabel } from "./plan-contract.js";
import type { TemplatePlan } from "./plan-types.js";

/** 人間確認用の変換計画 Markdown（docs/template-import-plan.md） */
export function renderPlanMarkdown(plan: TemplatePlan): string {
  const lines: string[] = [];
  const push = (s = ""): void => {
    lines.push(s);
  };

  push("# Template Import Plan");
  push();
  push(`- Source: \`${plan.source}\``);
  push(
    `- Manifest fingerprint: \`${plan.manifest_fingerprint.slice(0, 16)}…\``,
  );
  push(`- Generated by: ${plan.generated_by}（Manifest からの決定論生成）`);
  push(
    `- Entry (home): ${plan.entry ? `\`${plan.entry}\`` : "**未決定 — REVIEW**（\`template inspect --entry <file>\` で指定）"}`,
  );
  push();
  push(
    "> confidence: **CONFIDENT** = 自動変換 / **REVIEW** = 変換するが人間確認推奨 / **UNKNOWN** = 変換しない",
  );

  /*
   * **いちばん重い変更を、いちばん上に出す**（R-13 Stage 2）。
   *
   * 投稿タイプの新設はテーブルを作る不可逆な操作で、**ID はあとから変えられない**。
   * plan の承認がその門なので、承認する人が**読まずに通せない位置**へ置く。
   * ここに出ていなければ、plan に書いてあっても「明記した」ことにならない。
   */
  if (plan.content_types.length > 0) {
    push();
    push("## 投稿タイプ（この取り込みが使う CMS 管理の型）");
    push();
    push(
      "> **ID はあとから変更できません**（公開 URL とデータのキーになります）。表示名はいつでも変えられます。",
    );
    push();
    push("| ID | 表示名 | 構成 | 確度 |");
    push("| --- | --- | --- | --- |");

    for (const t of plan.content_types) {
      push(`| \`${t.id}\` | ${t.label} | ${t.preset} | ${t.confidence} |`);
    }

    push();

    for (const t of plan.content_types) {
      push(`- \`${t.id}\`: ${t.reason}`);
    }
  }

  push();
  push("## Pages");
  push();
  for (const p of plan.pages) {
    push(`### \`${p.source}\` → \`${p.target}\` [${p.confidence}]`);
    push();
    push(`- route: ${p.route ? `\`${p.route}\` (${p.url})` : "（未対応）"}`);
    if (p.integrations.length > 0)
      push(`- CMS 統合: ${p.integrations.join(", ")}`);
    push(`- 理由: ${p.reason}`);
    push();
  }

  push("## Layout / Shared Components");
  push();
  push(`- 共通レイアウト → \`${plan.layout.target}\``);
  push(`  - ${plan.layout.reason}`);
  for (const c of plan.components) {
    push(
      `- \`${c.source_pattern}\`（${c.source_pages.join(", ")}）→ \`${c.target_blade}\` [${c.confidence}]`,
    );
    push(`  - ${c.reason}`);
  }

  push();
  push("## CMS Integrations");
  push();
  for (const i of plan.cms_integrations) {
    push(`### ${i.id} → \`${i.schema}\` schema [${i.confidence}]`);
    push();
    push(
      `- 対象: ${i.regions.map((r) => `${r.page} \`${r.container}\``).join(" / ")}`,
    );
    push(`- フィールド対応:`);
    for (const [from, to] of Object.entries(i.field_mapping)) {
      push(`  - \`${from}\` → \`${to}\``);
    }
    for (const c of i.server_constants) {
      push(
        `  - \`${c.key}\` = constant("${c.value}")（server-side — ${c.note}）`,
      );
    }
    for (const u of i.unmapped_html_fields) {
      push(`- ⚠ 未対応 HTML フィールド \`${u.name}\`: ${u.handling}`);
    }
    for (const m of i.missing_schema_fields) {
      push(`- schema フィールド \`${m.key}\`: ${m.note}`);
    }
    push(`- 理由: ${i.reason}`);
    push();
  }

  if (plan.schema_changes.length > 0) {
    push("## Schema Changes（project scope — Core は変更しない）");
    push();
    for (const s of plan.schema_changes) {
      const values =
        s.values.length > 0
          ? `: ${s.values.map((v) => `\`${v}\``).join(", ")}`
          : "";
      push(
        `- \`${s.schema}.${s.field}\` ${s.change}${values} [${s.confidence}] (scope: ${s.scope})`,
      );
      push(`  - ${s.reason}`);
    }
    push();
  }

  if ((plan.taxonomy_changes ?? []).length > 0) {
    push(
      "## 分類項目の提案（project scope — 承認して apply するまで作成しません）",
    );
    push();
    push("| 分類 | 取り込んだ値 | 件数 | 名前 | slug | 既存との照合 | 確度 |");
    push("| --- | --- | --- | --- | --- | --- | --- |");
    for (const c of plan.taxonomy_changes) {
      const match =
        c.match.kind === "active" || c.match.kind === "archived"
          ? `${matchLabel(c.match)}（${c.match.term_id}）`
          : matchLabel(c.match);
      push(
        `| \`${c.taxonomy}\` | ${c.source_value} | ${c.occurrences} | ${c.proposed_name} | ${
          c.proposed_slug === null
            ? "—（決められない）"
            : `\`${c.proposed_slug}\``
        } | ${match} | ${c.confidence} |`,
      );
    }
    push();
    for (const c of plan.taxonomy_changes) {
      push(`- \`${c.taxonomy}\` / ${c.source_value}: ${c.reason}`);
    }
    push();
  }

  push("## Keep Static");
  push();
  for (const k of plan.keep_static) {
    push(`- ${k.page} \`${k.region}\` [${k.confidence}] — ${k.reason}`);
  }

  push();
  push("## JavaScript");
  push();
  for (const j of plan.javascript) {
    push(`- \`${j.file}\`（${j.action}）[${j.confidence}] — ${j.reason}`);
  }

  push();
  push("## Assets");
  push();
  push(
    `- static asset ${plan.assets.static.length} 件 → \`public/${plan.assets.target_prefix}/\`（元のディレクトリ構造を保持）`,
  );
  push(
    `- Content Media ${plan.assets.media.length} 件 → Media Library へ登録（CMS 統合された繰り返しのコンテンツ画像のみ）:`,
  );
  for (const m of plan.assets.media) {
    push(`  - \`${m.from}\` → "${m.name}"`);
  }
  if (plan.assets.excluded.length > 0) {
    push(
      `- copy しない asset ${plan.assets.excluded.length} 件（Reference-Based Asset Allowlist — 未参照・制作/文書ファイルは公開しない）:`,
    );
    for (const e of plan.assets.excluded) {
      push(`  - \`${e.path}\` [${e.kind}] — ${e.reason}`);
    }
  }

  if (Object.keys(plan.env_additions).length > 0) {
    push();
    push("## CSP / .env 追記（外部依存の許可）");
    push();
    for (const [key, value] of Object.entries(plan.env_additions)) {
      push(`- \`${key}=${value}\``);
    }
  }

  if (plan.uncertainties.length > 0) {
    push();
    push("## Uncertainties（要確認）");
    push();
    for (const u of plan.uncertainties) {
      push(`- [${u.level}] ${u.subject} — ${u.note}`);
    }
  }

  if (plan.warnings.length > 0) {
    push();
    push("## Warnings（inspect より）");
    push();
    for (const w of plan.warnings) {
      push(`- [${w.kind}] \`${w.file}\`: ${w.message}`);
    }
  }

  push();
  return lines.join("\n");
}
