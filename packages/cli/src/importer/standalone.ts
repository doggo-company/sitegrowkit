/**
 * 標準規約外ページの route。**layout モードからも呼ぶ**（監査 指摘 33）。
 *
 * これを standalone モードだけが呼んでいたので、**layout モードでは
 * 汎用ページの view を書くのに route を登録していなかった** —
 * 生成した Blade の `route('works')` がどこにも当たらず例外になる。
 */
/**
 * 詳細ページへのリンクの書き方を、**plan に聞く**（R-13 8 件目）。
 *
 * CMS が持つ投稿タイプの公開面は `Route::fallback` が受けるので、
 * 名前付き route は存在しない。`route('works.show', …)` を書くと
 * **公開ページが `Route [works.show] not defined` で 500 になる**（実案件で実測）。
 */
function detailHref(
  plan: TemplatePlan,
  integrationId: string,
  schemaFallback: string,
  slugExpr: string,
): string {
  const integration = plan.cms_integrations.find((i) => i.id === integrationId);
  const route = integration?.detail_route;
  const type = integration?.schema ?? schemaFallback;

  return route === null || route === undefined
    ? `/${type}/{{ ${slugExpr} }}`
    : `{{ route('${route}', ${slugExpr}) }}`;
}

export function generateImportedRoutes(pages: PagePlan[], fp: string): string {
  const routes = pages
    .map((p) => {
      const view = p.target
        .replace(/^resources\/views\//, "")
        .replace(/\.blade\.php$/, "")
        .replaceAll("/", ".");
      const slug = importedPageSlug(p.url ?? "");
      /*
       * **`Route::view` にしない**（R03 続き (1)）。静的な view を直に返すと、取り込みで作った
       * ページを管理画面で直しても**元の URL には出ない**。`ImportedPageController` が
       * 結び付いたページ（`imported_page_layouts`）を先に見て、無ければ静的な view を出す。
       */
      const layout = slug === null ? "" : `->defaults('layout', 'layouts.preserved.${slug}')`;

      return `    Route::get('${p.url}', ImportedPageController::class)->defaults('view', '${view}')${layout}->name('${p.route}');`;
    })
    .join("\n");
  return `<?php

// generated by agentcms template apply — 標準規約外ページの route（source fingerprint ${fp}）
// 手動編集すると再 apply 時に conflict になります

use AgentCms\\Core\\Http\\PublicCspMiddleware;
use App\\Http\\Controllers\\ImportedPageController;
use Illuminate\\Support\\Facades\\Route;

Route::middleware(PublicCspMiddleware::class)->group(function (): void {
${routes}
});
`;
}

