function relPathOf(ancestor: HTMLElement, el: HTMLElement): number[] | null {
  const path: number[] = [];
  let cur: HTMLElement = el;
  while (cur !== ancestor) {
    const parent = cur.parentNode;
    if (!(parent instanceof HTMLElement)) return null;
    const siblings = parent.childNodes.filter(
      (c): c is HTMLElement => c instanceof HTMLElement,
    );
    path.unshift(siblings.indexOf(cur));
    cur = parent;
  }
  return path;
}

function atRelPath(ancestor: HTMLElement, path: number[]): HTMLElement | null {
  return atPath(ancestor, path);
}
