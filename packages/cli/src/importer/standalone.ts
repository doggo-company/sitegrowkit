/**
 * Standalone（preserve）モード — 共通 header/footer が抽出できない実案件向けの生成。
 * layout へ分解せず、原 HTML 文書全体（inline <style> / <script> / nav / 装飾を含む）を
 * そのまま Blade 化する。変換は CMS スロット注入と参照書き換えのみ（Preserve First）。
 */
export function generateStandalonePages(
  sourceDir: string,
  manifest: Manifest,
  plan: TemplatePlan,
): { files: GeneratedFile[] } {
  const files: GeneratedFile[] = [];
  const fp = manifest.fingerprint.total.slice(0, 12);
  const stamp = (source: string): string =>
    `{{-- generated by agentcms template apply (standalone/preserve mode) — source: ${source} (fingerprint ${fp}) — 手動編集すると再 apply 時に conflict になります --}}\n`;

  const doneTargets = new Set<string>();
  const importedRoutes: PagePlan[] = [];

  for (const pagePlan of plan.pages) {
    /*
     * 行き先が決まっていないページは生成しない。
     *
     * **見るのは `url` であって `route` ではない**（R-13 8 件目）。
     * CMS が持つ投稿タイプのページは `Route::fallback` が受けるので
     * **名前付き route を持たない**（`route: null` / `url: "/works"`）。
     * route で判定すると、そのページを**丸ごと生成しなくなる**。
     */
    if (pagePlan.url === null) continue;
    if (doneTargets.has(pagePlan.target)) continue;
    doneTargets.add(pagePlan.target);

    // 詳細ページ（`/works/{slug}`）。名前付き route の有無で判定しない
    if (pagePlan.url.includes("{slug}")) {
      files.push({
        target: pagePlan.target,
        content:
          stamp(
            `works detail pages (${detailSeeds(plan)
              .map((w) => w.source_page)
              .join(", ")})`,
          ) + generateWorksShow(sourceDir, plan, files),
        source: "works detail pages",
      });
      continue;
    }

    files.push({
      target: pagePlan.target,
      content:
        stamp(pagePlan.source) +
        generateStandalonePage(sourceDir, plan, pagePlan, files),
      source: pagePlan.source,
    });

    /*
     * 名前付き route を持つページだけが `routes/imported.php` へ載る。
     * CMS が持つ型のページ（`route: null`）は fallback が受けるので載せない。
     */
    if (pagePlan.route !== null && !BUILTIN_ROUTES.has(pagePlan.route)) {
      importedRoutes.push(pagePlan);
    }
  }

  if (importedRoutes.length > 0) {
    files.push({
      target: "routes/imported.php",
      content: generateImportedRoutes(importedRoutes, fp),
      source: "plan pages（標準規約外 route）",
    });
  }

  /*
   * ---- 取り込んだ意匠の CMS フォーム（R-12 Stage 2 / D）----
   *
   * 同じ原本から**もう 1 通り**書き出す。旧 Contact パイプラインへ繋いだものは
   * そのまま残し、こちらは **CMS のフォーム**を取り込んだ意匠で描く。
   * `ContactEntry` は**この view が在るかどうか**で切り替えを決めるので、
   * **書けた案件だけ**が切り替わる。
   *
   * ▷ **layout モードと同じものを、こちらにも置く。** 最初は layout 側にだけ書いていて、
   *   **standalone の案件では 1 ファイルも書かれなかった** — 同梱見本が
   *   layout モードなので、試験も layout 側しか通っていなかった（2026-08-28 に実測）。
   */
  const contactPage = plan.pages.find((page) =>
    plan.cms_integrations.some(
      (i) =>
        i.id === "contact-form" && i.regions.some((r) => r.page === page.source),
    ),
  );

  if (contactPage !== undefined) {
    const partial = "forms.partials.imported-control";

    files.push({
      target: "resources/views/forms/imported.blade.php",
      content:
        stamp(contactPage.source) +
        generateStandalonePage(sourceDir, plan, contactPage, [], { partial }),
      source: contactPage.source,
    });

    const template = extractFieldTemplate(
      parseSource(sourceDir, contactPage.source).querySelector(
        plan.cms_integrations
          .find((i) => i.id === "contact-form")!
          .regions.find((r) => r.page === contactPage.source)!.container,
      ),
    );

    if (template !== null) {
      files.push({
        target: "resources/views/forms/partials/imported-control.blade.php",
        content: buildControlPartial(template),
        source: contactPage.source,
      });
    }
  }

  return { files };
}

function detailSeeds(plan: TemplatePlan): CardSeed[] {
  return cardRows(plan).filter(
    (w) => typeof w.source_page === "string" && w.source_page.length > 0,
  );
}

// ---- 通常ページ（full-document passthrough + スロット注入） ----

/**
 * ナビの並びの場所。**`<nav>` の中の最初の `<ul>`**。
 *
 * 案件ごとの class 名（`nav-links` 等）に依らない形にしてある。
 */
const NAV_LIST = "nav ul";

/**
 * フッターの導線の入れ物。**`<footer>` の中で `<a>` を一番多く持つ器**……
 * ではなく、**`<footer>` そのもの**を渡す。
 *
 * 入れ物の class は案件ごとに違う（実案件は `footer-sticker-alt`）。
 * `<footer>` を渡せば、その中の最初の `<a>` から最後の `</a>` までが並びになる。
 *
 * ▷ **住所やコピーライトの中に `<a>` があると、そこまで巻き込む。**
 *   実案件では巻き込まないことを実測で確かめてある。
 *   巻き込む案件が出たら、そこで入れ物を絞る判断をする（先に一般化しない）。
 */
const FOOTER_NAV = "footer";

/**
 * その文書の `<head>` に、検索と共有に必要な tag を足す。
 *
 * **原本が既に持っているものは足さない**（`seoTags()` が判断する）。
 */
function addSeoTags(root: HTMLElement): void {
  const head = root.querySelector("head");

  if (head === null) return;

  const tags = seoTags(head.innerHTML);

  if (tags !== "") head.insertAdjacentHTML("beforeend", `${tags}\n`);
}

function generateStandalonePage(
  sourceDir: string,
  plan: TemplatePlan,
  pagePlan: PagePlan,
  extras: GeneratedFile[],
  /**
   * フォームを **CMS の項目**で描く（R-12 Stage 2 / D）。
   *
   * 同じ原本から**2 通り**書き出す — 旧 Contact パイプラインへ繋いだものと、
   * CMS のフォームへ繋いだもの。**原本は 1 つなので、意匠は必ず一致する。**
   */
  cmsForm?: { partial: string },
): string {
  const pageSource = pagePlan.source;
  const root = parseSource(sourceDir, pageSource);
  const phpBlocks: [string, string][] = [];

  const integrations = plan.cms_integrations.filter((i) =>
    i.regions.some((r) => r.page === pageSource),
  );
  for (const integration of integrations) {
    const region = integration.regions.find((r) => r.page === pageSource)!;
    if (integration.id === "works-cards") {
      const php = substituteWorksCardsLinked(
        root,
        region.container,
        region.item ?? "",
        detailSeeds(plan),
        "$works",
        pageSource,
        plan,
      );
      if (php) phpBlocks.push(php);
    } else if (integration.id === "news-list") {
      const listVar = pageSource === plan.entry ? "$news" : "$items";
      substituteNewsDated(
        root,
        region.container,
        region.item ?? "",
        plan,
        listVar,
      );
    } else if (integration.id === "contact-form") {
      if (cmsForm !== undefined) {
        const template = extractFieldTemplate(
          root.querySelector(region.container),
        );

        if (template !== null) {
          substituteCmsForm(root, region.container, template, cmsForm.partial);
        }
      } else {
        substituteContactForm(root, region.container, integration.field_mapping);
      }
      root
        .querySelector("head")
        ?.insertAdjacentHTML(
          "beforeend",
          '\n    <script src="https://challenges.cloudflare.com/turnstile/v0/api.js" async defer></script>\n',
        );
    }
  }

  /*
   * ---- 取り込んだナビを CMS のメニューへ繋ぐ（B-56）----
   *
   * 🔴 **layout 1 枚では足りない。**standalone はページごとに html を丸ごと持つので、
   * ナビも**ページの数だけ複製されている**（実案件で 12 ファイル・実測）。
   * 生成のここで全ページに掛ける。
   *
   * ▷ **場所は構造で決める。**`plan` に selector を持たせない —
   *   案件ごとに書く欄が増えるだけで、**書き忘れたら黙って効かなくなる**。
   *   「`<nav>` の中の最初の `<ul>`」は原本の書き方に依らず成り立つ。
   *
   * ▷ **見つからなければ何もしない。**ナビの形が案件ごとに違うので、
   *   「取れなかった」は普通に起こる（実案件の footer は `<ul>` を使っていない）。
   *   取れないまま切るとナビごと消える。
   */
  substituteImportedNav(root, NAV_LIST, "header");
  substituteImportedFooterNav(root, FOOTER_NAV, "footer");

  /*
   * 🔴 **検索と共有に必要な tag は、ページごとに足す。**
   *
   * standalone は**ページごとに html を丸ごと持つ**ので、layout を 1 枚直しても
   * **トップしか直らない**（2026-08-28 実測。7 ページが 0 件のまま残った）。
   * ナビと同じで、**ここで全ページに掛ける。**
   */
  addSeoTags(root);

  externalizeInlineScripts(root, pageSource, plan, extras);
  externalizeInlineHandlers(root, pageSource, plan, extras);
  rewriteRefs(root, pageSource, plan);
  rewriteInlineCssUrls(root, pageSource, plan);

  /*
   * 🔴 **`@php(...)` の短い形を出さない。**
   *
   * Blade は `@php ... @endphp` を**ファイル全体から先に拾う**（`storePhpBlocks`）。
   * そこに `@php(` も引っかかるので、**短い形がブロック形より前に 1 つでもあると、
   * そこから最初の `@endphp` までが丸ごと 1 つの PHP ブロックとして食われる。**
   *
   * 施工事例の詳細 view は先頭に短い形が 2 つ、294 行目にブロック形が 1 つあり、
   * **生成した時点から全ページ 500 だった**（2026-08-28 実測。
   * 古いコンパイル結果が残っていたので、しばらく気づけなかった）。
   *
   * **全部ブロック形で出す。**そうすれば `@php` は必ず自分の `@endphp` と対になる。
   */
  // @php ブロックはプレースホルダー経由で挿入する（DOM に入れると HTML として再パースされ、
  // 文字列内の asset 参照が rewriteRefs に二重処理されるため）
  let out = `${root.toString().trim()}\n`;
  for (const [token, php] of phpBlocks) out = out.replace(token, php);
  return addSelectedDirectives(out);
}

/** 日付 + テキスト形式の news 繰り返し → @foreach（time 要素なしの実案件対応） */
function substituteNewsDated(
  root: HTMLElement,
  containerSelector: string,
  itemSig: string,
  plan: TemplatePlan,
  listVar: string,
): void {
  const container = root.querySelector(containerSelector);
  if (!container) return;
  const items = childrenBySig(container, itemSig);
  const first = items[0];
  const seed = datedRows(plan)[0];
  if (!first || !seed) return;

  const dateDot = seed.date.replaceAll("-", ".");
  const leaves = [first, ...first.querySelectorAll("*")].filter(
    (el) => !el.childNodes.some((c) => c instanceof HTMLElement),
  );
  let titleDone = false;
  for (const el of leaves) {
    const t = el.text.trim();
    if (t === dateDot) {
      el.set_content("{{ $item->published_at?->format('Y.m.d') }}");
    } else if (t === seed.title) {
      el.set_content("{{ $item->title }}");
      titleDone = true;
    }
  }
  if (!titleDone) {
    // サブページ側は同一記事のテキストが延長されているため、残る本文 leaf を title へ
    for (const el of leaves) {
      const t = el.text.trim();
      if (t && !t.includes("{{")) {
        el.set_content("{{ $item->title }}");
        break;
      }
    }
  }

  const tpl = first.outerHTML.trim();
  first.replaceWith(
    `\n@foreach (${listVar} as $item)\n${indent(tpl, 2)}\n@endforeach\n`,
  );
  for (const el of items.slice(1)) el.remove();
}

/** 詳細ページリンク付き works カード → @foreach（連番・装飾のバリエーションを保持） */
function substituteWorksCardsLinked(
  root: HTMLElement,
  containerSelector: string,
  itemSig: string,
  seeds: CardSeed[],
  listVar: string,
  pageSource: string,
  plan: TemplatePlan,
): [string, string] | null {
  const container = root.querySelector(containerSelector);
  if (!container) return null;
  const items = childrenBySig(container, itemSig);
  const first = items[0];
  const seed0 = seeds[0];
  if (!first || !seed0) return null;

  const detailSet = new Set(seeds.map((w) => w.source_page));

  // テキスト slot（title / excerpt / 連番）
  const leaves = [first, ...first.querySelectorAll("*")].filter(
    (el) => !el.childNodes.some((c) => c instanceof HTMLElement),
  );
  for (const el of leaves) {
    const t = el.text.trim();
    if (t === seed0.title) {
      el.set_content("{{ $work->title }}");
    } else if (seed0.excerpt && t === seed0.excerpt.trim()) {
      el.set_content("{{ $work->excerpt }}");
    } else if (/^\d+$/.test(t) && Number(t) === 1) {
      // 連番: 各 item の対応要素がその序数なら loop 連番へ
      const rp = relPathOf(first, el);
      const ordinal = items.every((it, k) => {
        const other = rp ? atRelPath(it, rp) : null;
        return (
          other !== null &&
          other.text.trim() === String(k + 1).padStart(t.length, "0")
        );
      });
      if (ordinal)
        el.set_content(`{{ sprintf('%0${t.length}d', $loop->iteration) }}`);
    }
  }

  // メイン画像・詳細リンク
  for (const img of first.querySelectorAll("img[src]")) {
    const src = img.getAttribute("src") ?? "";
    const resolved = resolveRelative(pageSource, src) ?? src;
    if (resolved === seed0.image) {
      img.setAttribute("src", "{{ $work->mainImage?->url() }}");
      if ((img.getAttribute("alt") ?? "").trim() === seed0.title)
        img.setAttribute("alt", "{{ $work->title }}");
    }
  }
  for (const a of first.querySelectorAll("a[href]")) {
    const href = a.getAttribute("href") ?? "";
    const resolved = resolveRelative(pageSource, href) ?? href;
    if (detailSet.has(resolved))
      a.setAttribute(
        "href",
        detailHref(plan, "works-cards", "works", "$work->slug"),
      );
  }

  // item ごとに異なる装飾サブツリー（aria-hidden）は配列サイクルで完全保持する
  const decoArrays: string[] = [];
  for (const el of first.querySelectorAll('[aria-hidden="true"]')) {
    const rp = relPathOf(first, el);
    if (!rp) continue;
    const variants = items.map((it) => atRelPath(it, rp));
    if (variants.some((v) => v === null)) continue;
    const htmls = variants.map((v) => v!.outerHTML.replace(/\s+/g, " ").trim());
    if (new Set(htmls).size <= 1) continue;
    const phpHtmls = htmls.map((h) =>
      h.replace(/src="([^"]+)"/g, (all: string, ref: string) => {
        if (/^(https?:)?\/\//.test(ref) || ref.startsWith("data:")) return all;
        const resolved = resolveRelative(pageSource, ref) ?? ref;
        return `src="/${plan.assets.target_prefix}/${resolved}"`;
      }),
    );
    const idx = decoArrays.length;
    decoArrays.push(`[${phpHtmls.map((h) => `'${phpString(h)}'`).join(", ")}]`);
    el.replaceWith(
      `{!! $__workDecos[${idx}][$loop->index % count($__workDecos[${idx}])] !!}`,
    );
  }

  const tpl = first.outerHTML.trim();
  // @php の中身（PHP 文字列としての HTML）を DOM に入れると再パースされるため、
  // トークンだけを DOM へ置き、toString() 後に本体へ差し替える
  const token = "__AGENTCMS_WORK_DECOS__";
  const pre = decoArrays.length > 0 ? `${token}\n` : "";
  first.replaceWith(
    `\n${pre}@foreach (${listVar} as $work)\n${indent(tpl, 2)}\n@endforeach\n`,
  );
  for (const el of items.slice(1)) el.remove();
  return decoArrays.length > 0
    ? [token, `@php\n$__workDecos = [${decoArrays.join(", ")}];\n@endphp`]
    : null;
}

// ---- works show（詳細ページ N 件 → 単一テンプレート統合） ----

/**
 * 詳細ページ間の差分（title / 連番 / 画像 / ナビの current）だけを Blade スロット化する。
 * 差分がこの範囲で説明できない場合は throw（STOP — 無理に統合して fidelity を失わない）。
 */
function generateWorksShow(
  sourceDir: string,
  plan: TemplatePlan,
  extras: GeneratedFile[],
): string {
  const seeds = detailSeeds(plan);
  const pages = seeds.map((w) => w.source_page!);
  const roots = pages.map((p) => parseSource(sourceDir, p));
  const shell = roots[0]!;
  const shellPage = pages[0]!;

  const counts = roots.map((r) => r.querySelectorAll("*").length);
  if (new Set(counts).size !== 1) {
    throw new Error(
      `works 詳細ページの DOM 構造が一致しません（要素数: ${counts.join(", ")}）— 単一 show テンプレートへ統合できないため STOP。ページ別の static 保持を検討してください`,
    );
  }

  // 1. 詳細ナビ（全詳細ページへのリンクを含む最小の要素）→ 動的化
  const navCandidates = [...shell.querySelectorAll("*")]
    .filter((el) => {
      const hrefs = el
        .querySelectorAll("a[href]")
        .map(
          (a) =>
            resolveRelative(shellPage, a.getAttribute("href") ?? "") ??
            a.getAttribute("href") ??
            "",
        );
      return pages.every((p) => hrefs.includes(p));
    })
    .sort(
      (a, b) => a.querySelectorAll("*").length - b.querySelectorAll("*").length,
    );
  const navEl = navCandidates[0] ?? null;
  if (navEl) {
    const links = navEl.querySelectorAll("a[href]");
    const detailLinks = links.filter((a) =>
      pages.includes(
        resolveRelative(shellPage, a.getAttribute("href") ?? "") ?? "",
      ),
    );
    const firstLink = detailLinks[0]!;
    const width = /\d+/.exec(firstLink.text)?.[0]?.length ?? 2;
    const labelTpl = firstLink.text
      .trim()
      .replace(/\d+/, `{{ sprintf('%0${width}d', $__i + 1) }}`);
    const others = links
      .filter((a) => !detailLinks.includes(a))
      .map((a) => a.outerHTML.trim());
    // class 属性は quoted Blade 式にする（属性位置の {!! !!} はパーサ再解析で壊れる）
    navEl.set_content(
      `\n@foreach ($__works as $__i => $__w)\n  <a href="${detailHref(plan, "works-cards", "works", "$__w->slug")}" class="{{ $__w->is($item) ? 'current' : '' }}">${labelTpl}</a>\n@endforeach\n${others.join("\n")}\n`,
    );
  }
  // nav 配下は動的化済み — 以降の diff 比較から除外する
  const navScope = new Set<HTMLElement>(
    navEl ? [navEl, ...navEl.querySelectorAll("*")] : [],
  );

  // 2. テキスト slot: 全ページ比較で「title + 連番」の同時置換として説明できる差分のみ許可
  const unresolved: string[] = [];
  const T = "\0T\0";
  for (const el of [...shell.querySelectorAll("*")]) {
    if (navScope.has(el)) continue;
    if (el.childNodes.some((c) => c instanceof HTMLElement)) continue;
    const p = pathOf(el);
    const texts = roots.map((r) => atPath(r, p)?.text.trim() ?? null);
    if (texts.some((t) => t === null)) continue;
    if (new Set(texts).size === 1) continue;
    const t0 = texts[0]!;
    if (t0.includes("{{") || t0.includes("@foreach")) continue; // ナビ動的化済み

    // マーカー化: title → T、序数 (01 等) → N<width>
    let tpl = t0;
    if (seeds[0]!.title) tpl = tpl.replaceAll(seeds[0]!.title, T);
    const widths: number[] = [];
    tpl = tpl.replace(/\d+/g, (run) => {
      if (Number(run) === 1) {
        widths.push(run.length);
        return `\0N${run.length}\0`;
      }
      return run;
    });
    const renders = seeds.map((w, k) => {
      let s = tpl.replaceAll(T, w.title);
      s = s.replace(/\0N(\d+)\0/g, (_m, wd: string) =>
        String(k + 1).padStart(Number(wd), "0"),
      );
      return s;
    });
    if (renders.every((s, k) => s === texts[k])) {
      const blade = tpl
        .replaceAll(T, "{{ $item->title }}")
        .replace(
          /\0N(\d+)\0/g,
          (_m, wd: string) => `{{ sprintf('%0${wd}d', $__num) }}`,
        );
      el.set_content(blade);
    } else {
      unresolved.push(`${el.tagName.toLowerCase()}: "${t0.slice(0, 60)}"`);
    }
  }

  // 3. メイン画像 slot
  for (const img of shell.querySelectorAll("img[src]")) {
    if (navScope.has(img)) continue;
    const p = pathOf(img);
    const srcs = roots.map((r, k) => {
      const other = atPath(r, p);
      const src = other?.getAttribute("src") ?? "";
      return resolveRelative(pages[k]!, src) ?? src;
    });
    if (new Set(srcs).size === 1) continue;
    if (srcs.every((s, k) => s === seeds[k]!.image)) {
      img.setAttribute("src", "{{ $item->mainImage?->url() }}");
      const alts = roots.map((r) => atPath(r, p)?.getAttribute("alt") ?? "");
      if (alts.every((a, k) => a.trim() === seeds[k]!.title))
        img.setAttribute("alt", "{{ $item->title }}");
    } else {
      unresolved.push(`img: ${srcs.join(" / ")}`);
    }
  }

  if (unresolved.length > 0) {
    throw new Error(
      `works 詳細ページに title / 連番 / 画像で説明できない差分があります — STOP（fidelity を失う統合はしない）:\n${unresolved.join("\n")}`,
    );
  }

  /*
   * 🔴 **詳細ページも同じ。**ここは `generateStandalonePage()` を通らない別経路なので、
   * 繋ぎ忘れるとこのページだけナビが焼き付いたまま残る（実際に試験が拾った）。
   */
  substituteImportedNav(shell, NAV_LIST, "header");
  substituteImportedFooterNav(shell, FOOTER_NAV, "footer");
  addSeoTags(shell);

  externalizeInlineScripts(shell, shellPage, plan, extras);
  externalizeInlineHandlers(shell, shellPage, plan, extras);
  rewriteRefs(shell, shellPage, plan);
  rewriteInlineCssUrls(shell, shellPage, plan);

  /*
   * **投入先のクラスは plan が知っている**（R-13 12 件目）。
   *
   * CMS が作った型は `Modules\\Works\\Models\\Works`（Studly を 2 度）、
   * kit の例は `…\\Models\\Work`（単数）で**別のクラス**である。
   * ここを決め打つと、CMS が作った型の詳細ページが
   * **存在しないクラスを呼んで 500** になる（実案件で実測）。
   */
  const model = cardsOf(plan)?.model ?? "Modules\\Works\\Models\\Work";

  const header = [
    `@php\n$__works = \\${model}::published()->orderByDesc('published_at')->get();\n@endphp`,
    "@php\n$__num = (int) $__works->search(fn ($__w) => $__w->is($item)) + 1;\n@endphp",
  ].join("\n");
  return `${header}\n${shell.toString().trim()}\n`;
}

/**
 * inline <script> を外部ファイルへ抽出する。
 * Core の公開 CSP は inline script を許可しないため、実案件の inline JS
 * （nav toggle / slider / reveal / フォント loader 等）はそのままでは全てブロックされる。
 * 実行位置・順序を保つため、同じ DOM 位置を <script src> へ置き換える（コードは無変更）。
 */
function externalizeInlineScripts(
  root: HTMLElement,
  pageSource: string,
  plan: TemplatePlan,
  extras: GeneratedFile[],
): void {
  const pageName = (pageSource.split("/").pop() ?? pageSource)
    .replace(/\.html?$/, "")
    .replace(/[^a-z0-9-]/gi, "-")
    .toLowerCase();
  let idx = 0;
  for (const s of root.querySelectorAll("script")) {
    if (s.getAttribute("src")) continue;
    const type = s.getAttribute("type");
    if (type && !/javascript|module/i.test(type)) continue; // JSON-LD 等は実行されないので保持
    if (!s.text.trim()) continue;
    idx += 1;
    const file = `js/${pageName}-inline-${idx}.js`;
    extras.push({
      target: `public/${plan.assets.target_prefix}/${file}`,
      content: `// generated by agentcms template apply — ${pageSource} の inline <script> #${idx}（CSP 対応の外部化。コードは無変更）\n${s.text}`,
      source: `${pageSource} inline <script> #${idx}`,
    });
    s.set_content("");
    s.setAttribute(
      "src",
      `{{ asset('${plan.assets.target_prefix}/${file}') }}`,
    );
  }
}

/**
 * inline イベントハンドラ属性（onclick 等）を addEventListener 委譲へ変換する。
 * CSP は script ブロックだけでなくハンドラ属性の実行もブロックするため、
 * data 属性でマークして同等のリスナーを外部 JS で登録する（this / event の意味は保たれる）。
 */
function externalizeInlineHandlers(
  root: HTMLElement,
  pageSource: string,
  plan: TemplatePlan,
  extras: GeneratedFile[],
): void {
  const pageName = (pageSource.split("/").pop() ?? pageSource)
    .replace(/\.html?$/, "")
    .replace(/[^a-z0-9-]/gi, "-")
    .toLowerCase();
  const regs: string[] = [];
  let n = 0;
  for (const el of root.querySelectorAll("*")) {
    const handlerAttrs = Object.entries(el.attributes).filter(
      ([name, value]) => /^on[a-z]+$/i.test(name) && value,
    );
    if (handlerAttrs.length === 0) continue;
    n += 1;
    const id = String(n);
    el.setAttribute("data-agentcms-ev", id);
    for (const [name, value] of handlerAttrs) {
      el.removeAttribute(name);
      const event = name.slice(2).toLowerCase();
      // inline handler の「return false = preventDefault」の意味論を保つ
      regs.push(
        `document.querySelectorAll('[data-agentcms-ev="${id}"]').forEach(function (el) {\n  el.addEventListener('${event}', function (event) {\n    var __r = (function (event) { ${value} }).call(this, event);\n    if (__r === false) event.preventDefault();\n  });\n});`,
      );
    }
  }
  if (regs.length === 0) return;
  const file = `js/${pageName}-handlers.js`;
  extras.push({
    target: `public/${plan.assets.target_prefix}/${file}`,
    content: `// generated by agentcms template apply — ${pageSource} の inline イベントハンドラ（CSP 対応の addEventListener 委譲。コードは無変更）\n${regs.join("\n")}\n`,
    source: `${pageSource} inline event handlers`,
  });
  (root.querySelector("body") ?? root).insertAdjacentHTML(
    "beforeend",
    `\n<script src="{{ asset('${plan.assets.target_prefix}/${file}') }}"></script>\n`,
  );
}

