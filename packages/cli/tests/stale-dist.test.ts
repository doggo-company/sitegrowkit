import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

import { BUNDLED_SAMPLE_MARK } from "../src/importer/bundled-samples.js";

/**
 * **利用者が実際に走らせるのは `dist/` である。**
 *
 * 🔴 **`src` を直しても `dist` を作り直さないと、何も起きない**
 * （2026-08-28 実測）。同梱の見本の目印を直した直後、
 * 試験は全部緑なのに、**使い捨ての案件を作ったら見本の一覧が 0 件だった。**
 *
 * 0 件だと `apply` が見本を飲まないので、**B-60（初回から conflict）がそのまま戻る。**
 * **しかもエラーは出ない。**「作れた」ように見える。
 *
 * ▷ **試験は `src` を読む。利用者は `dist` を読む。**この 2 つがずれても、
 *   ずれたこと自体は誰も言ってくれない。**ここで言う。**
 */
const DIST = join(import.meta.dirname, "..", "dist");

describe("dist が src から遅れていない", () => {
  it("dist が在る", () => {
    // 無いなら、そもそも配れない
    expect(existsSync(DIST)).toBe(true);
  });

  it("🔴 同梱の見本の目印が dist に届いている", () => {
    /*
     * **目印は 1 か所で決めている**（`BUNDLED_SAMPLE_MARK`）。
     * その値が dist に無いなら、**build を忘れている。**
     */
    const built = join(DIST, "importer", "bundled-samples.js");

    expect(existsSync(built)).toBe(true);
    expect(readFileSync(built, "utf-8")).toContain(BUNDLED_SAMPLE_MARK);
  });

  it("🔴 dist が src より古くない（build の忘れを丸ごと見る）", () => {
    /*
     * **目印 1 つを見るだけでは足りない。**次に何かを直したときは、
     * また同じ形で「試験は緑・利用者には届かない」が起きる。
     *
     * **一番新しい src と、一番新しい dist を比べる。**
     * src の方が新しければ、**build を忘れている。**
     */
    const newest = (dir: string): number => {
      let latest = 0;

      const walk = (d: string): void => {
        for (const entry of readdirSync(d)) {
          const abs = join(d, entry);
          const st = statSync(abs);

          if (st.isDirectory()) {
            walk(abs);

            continue;
          }

          latest = Math.max(latest, st.mtimeMs);
        }
      };

      walk(dir);

      return latest;
    };

    const src = newest(join(import.meta.dirname, "..", "src"));
    const dist = newest(DIST);

    expect(
      dist >= src,
      `dist が src より古い（src=${new Date(src).toISOString()} / dist=${new Date(dist).toISOString()}）。` +
        "`npm run build` を忘れている — 直したものが利用者には届かない",
    ).toBe(true);
  });

  it("素直でない例: 古い目印が dist に残っていない", () => {
    /*
     * 消し忘れると、**新旧どちらの目印でも数えてしまう。**
     * その状態は「動いている」ように見えるので、**気づけない。**
     */
    const built = readFileSync(join(DIST, "importer", "bundled-samples.js"), "utf-8");

    expect(built).not.toContain('= "generated by agentcms template apply"');
  });
});
