/**
 * 取り込んだ意匠で CMS のフォームを書き出す（R-12 Stage 2 / D-6）。
 *
 * ## 何を守るか
 *
 * `ContactEntry` は **`forms.imported` が在るかどうか**で切り替えを決める。
 * つまり**この 2 ファイルが書けた案件だけ**が、取り込み済みでもフォームへ切り替わる。
 * **書けていないのに切り替わる／書けたのに切り替わらない**、はどちらも事故になる。
 *
 * ## 同じ原本から 2 通り
 *
 * 旧 Contact パイプラインへ繋いだものは残したまま、CMS 版を**別ファイル**で足す。
 * 原本は 1 つなので、**意匠は必ず一致する**。
 */
import { readFileSync } from "node:fs";
import { join, resolve } from "node:path";

import { describe, expect, it } from "vitest";

import { generateFromPlan } from "../src/importer/generate.js";
import { buildPlan } from "../src/importer/plan.js";
import type { ContentSchema } from "../src/importer/plan-types.js";
import { analyzeTemplateDir } from "../src/inspect/analyze.js";

const FIXTURE = resolve(__dirname, "../../../examples/html-template");
const SCHEMAS = resolve(__dirname, "../../../template/content/schemas");

const loadSchema = (id: string): ContentSchema =>
  JSON.parse(readFileSync(join(SCHEMAS, `${id}.json`), "utf8")) as ContentSchema;

const manifest = analyzeTemplateDir(FIXTURE, "fixture");
const plan = buildPlan(manifest, {
  works: loadSchema("works"),
  news: loadSchema("news"),
  contact: loadSchema("contact"),
});
const files = new Map(
  generateFromPlan(FIXTURE, manifest, plan).files.map((f) => [f.target, f.content]),
);

/**
 * **standalone（preserve）モードでも書き出す。**
 *
 * ▷ **ここが抜けていた**（2026-08-28 に実測）。`generateFromPlan()` は
 * `layout.header_selector === null` のとき**早い段階で return する**ので、
 * layout モードにしか置いていなかった生成は **1 ファイルも走らなかった**。
 * **同梱見本が layout モードなので、試験も layout 側しか通っていなかった** —
 * 実案件（standalone）へ apply して初めて「2 ファイルとも無い」と分かった。
 *
 * 見本を standalone に倒して、**両方の枝**を通す。
 */
const standalonePlan = {
  ...plan,
  layout: { ...plan.layout, header_selector: null, footer_selector: null },
};
const standaloneFiles = new Map(
  generateFromPlan(FIXTURE, manifest, standalonePlan).files.map((f) => [
    f.target,
    f.content,
  ]),
);

const IMPORTED = "resources/views/forms/imported.blade.php";
const CONTROL = "resources/views/forms/partials/imported-control.blade.php";
const LEGACY = "modules/Contact/views/form.blade.php";

describe("取り込んだ意匠の CMS フォームを書き出す", () => {
  it("2 ファイルとも書き出す", () => {
    expect(files.has(IMPORTED)).toBe(true);
    expect(files.has(CONTROL)).toBe(true);
  });

  /** **旧側は残す。**片方だけにすると、切り替えを戻したいときに戻す先が無い */
  it("旧 Contact パイプラインの view も残る", () => {
    expect(files.has(LEGACY)).toBe(true);
    expect(files.get(LEGACY)).toContain("route('contact.store')");
  });

  it("CMS 版は項目を @foreach で描く", () => {
    const html = files.get(IMPORTED)!;

    expect(html).toContain("@foreach ($fields as $field)");
    expect(html).toContain('action="{{ $action }}"');
    expect(html).toContain("@include('forms.partials.imported-control'");
  });

  /** **旧側の繋ぎ方が混ざっていない**（同じ原本から書くので、取り違えると気づきにくい） */
  it("CMS 版に旧側の送信先は入らない", () => {
    const html = files.get(IMPORTED)!;

    expect(html).not.toContain("route('contact.store')");
    // 原本の項目名は残らない（項目は CMS が決める）
    expect(html).not.toContain('name="message"');
  });

  /** **受付を終了したフォームでは入力欄を出さない**（原本にはこの状態が無い） */
  it("受付終了の分岐を持つ", () => {
    const html = files.get(IMPORTED)!;

    expect(html).toContain("@if ($closed)");
    expect(html).toContain("このフォームは受付を終了しました。");
    expect(html).toContain("@endif");
  });

  /** **意匠が一致している**（同じ原本から書き出しているので、外側は同じもの） */
  it("原本の意匠が両方に残っている", () => {
    const cms = files.get(IMPORTED)!;
    const legacy = files.get(LEGACY)!;

    // 見本の連絡先セクションの class は、どちらにも在る
    for (const marker of ["contact-form", "page-title"]) {
      expect(cms).toContain(marker);
      expect(legacy).toContain(marker);
    }
  });

  it("制御要素の部品は外枠を出さない", () => {
    const partial = files.get(CONTROL)!;
    const code = partial.slice(partial.indexOf("--}}") + 4);

    expect(code).not.toContain('class="form-field"');
    expect(code).toContain("$field->type === 'textarea'");
  });

  /** **生成物だと分かる**（手で直すと再 apply で conflict になる） */
  it("生成物の目印を持つ", () => {
    expect(files.get(IMPORTED)).toContain("generated by agentcms template apply");
    expect(files.get(CONTROL)).toContain("生成物");
  });
});

describe("standalone（preserve）モードでも書き出す", () => {
  it("2 ファイルとも書き出す", () => {
    expect(standaloneFiles.has(IMPORTED)).toBe(true);
    expect(standaloneFiles.has(CONTROL)).toBe(true);
  });

  it("CMS 版は項目を @foreach で描く", () => {
    const html = standaloneFiles.get(IMPORTED)!;

    expect(html).toContain("@foreach ($fields as $field)");
    expect(html).toContain('action="{{ $action }}"');
    expect(html).toContain("@include('forms.partials.imported-control'");
  });

  /** **旧側は残す**（standalone でも同じ） */
  it("旧 Contact パイプラインの view も残る", () => {
    expect(standaloneFiles.get(LEGACY)).toContain("route('contact.store')");
  });

  it("CMS 版に旧側の送信先は入らない", () => {
    expect(standaloneFiles.get(IMPORTED)).not.toContain("route('contact.store')");
  });

  /** standalone は**丸ごと 1 枚の HTML** — 外側が落ちていないこと */
  it("原本のページごと出す（外側が落ちていない）", () => {
    // `content` は `string | Buffer`。blade は必ずテキストだが、型では
    // それを言えないので、文字列として見る前に 1 度だけ揃える
    const html = standaloneFiles.get(IMPORTED)!.toString();

    // 原本の綴り（大文字/小文字）に引きずられないよう、揃えてから見る
    expect(html.toLowerCase()).toContain("<!doctype html>");
    expect(html).toContain("</html>");
  });
});
