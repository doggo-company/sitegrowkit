import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";

import { classifyFiles, hashContent } from "../src/importer/apply.js";
import {
  BUNDLED_SAMPLES_PATH,
  collectBundledSamples,
} from "../src/importer/bundled-samples.js";

/**
 * kit が置いた見本を、利用者のものと取り違えない（B-60）。
 *
 * ここで固定するのは 4 つ:
 *   1. **触っていない見本は飲む**（初回 apply で conflict にしない）
 *   2. 🔴 **手が入っていたら飲まない**（利用者の直しを黙って消さない）
 *   3. **見本でないものは今までどおり conflict**
 *   4. **一覧が無い案件では、今までどおり**（古い案件を壊さない）
 */
const dirs: string[] = [];

function make(): string {
  const d = mkdtempSync(join(tmpdir(), "bundled-"));

  dirs.push(d);

  return d;
}

function put(root: string, rel: string, body: string): void {
  const p = join(root, rel);

  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, body);
}

const SAMPLE =
  "{{-- agentcms:bundled-sample — kit に同梱の見本サイトです。直して構いません --}}\n<p>見本</p>\n";

/**
 * 🔴 **素直でない例。**案件が自分で生成したものは**見本ではない。**
 *
 * 前は `generated by agentcms template apply` を目印にしていたので、
 * **これも見本として飲んでしまう**形だった（B-61）。
 * 飲むと、**利用者が自分の案件で生成したファイルが黙って上書きされる。**
 */
const PROJECT_GENERATED =
  "{{-- generated by agentcms template apply — source: index.html (fingerprint be16b2716b23) --}}\n<p>この案件のもの</p>\n";

afterEach(() => {
  for (const d of dirs.splice(0)) rmSync(d, { recursive: true, force: true });
});

describe("collectBundledSamples", () => {
  it("生成物の目印を持つものだけを集める", () => {
    const t = make();

    put(t, "resources/views/public/home.blade.php", SAMPLE);
    put(t, "resources/views/public/plain.blade.php", "<p>素の view</p>");

    expect(collectBundledSamples(t).map((s) => s.target)).toEqual([
      "resources/views/public/home.blade.php",
    ]);
  });

  it("🔴 案件が生成したものは見本として数えない", () => {
    /*
     * **見本と生成物は別物。**混ぜると、利用者が自分で生成したファイルを
     * 「kit の見本だから」と飲み込んで**黙って上書きする。**
     */
    const t = make();

    put(t, "resources/views/public/home.blade.php", PROJECT_GENERATED);

    expect(collectBundledSamples(t)).toEqual([]);
  });

  it("中身のハッシュを持つ", () => {
    const t = make();

    put(t, "modules/News/views/index.blade.php", SAMPLE);

    expect(collectBundledSamples(t)[0]!.sha256).toBe(hashContent(SAMPLE));
  });
});

describe("classifyFiles と同梱の見本", () => {
  /** 見本を置いた案件を作る */
  function project(body: string, samples = true): string {
    const p = make();

    put(p, "resources/views/public/home.blade.php", body);

    if (samples) {
      put(
        p,
        BUNDLED_SAMPLES_PATH,
        JSON.stringify([
          {
            target: "resources/views/public/home.blade.php",
            sha256: hashContent(SAMPLE),
          },
        ]),
      );
    }

    return p;
  }

  const generated = [
    {
      target: "resources/views/public/home.blade.php",
      content: "<p>この案件のもの</p>",
      source: "index.html",
    },
  ];

  it("触っていない見本は飲む（初回 apply が conflict にならない）", () => {
    // 🔴 飲まないと、**利用者は初回から `--force` を打つことになる**
    const states = classifyFiles(project(SAMPLE), generated, null);

    expect(states[0]!.state).toBe("ours");
    expect(states[0]!.wasSample).toBeUndefined();
  });

  it("🔴 手が入っていたら飲まない", () => {
    /*
     * 飲むと、**利用者の直しが黙って消える。**
     * 害の大きさより「黙って」の方が問題で、しかも**初めて触った日に起きる。**
     */
    const states = classifyFiles(
      project(`${SAMPLE}<p>利用者が足した</p>\n`),
      generated,
      null,
    );

    expect(states[0]!.state).toBe("foreign");
    expect(states[0]!.wasSample).toBe(true);
  });

  it("見本でないものは今までどおり conflict", () => {
    // **一覧に載っていない**ファイル（利用者が自分で作ったもの）
    const p = make();

    put(p, "resources/views/public/home.blade.php", "<p>手で書いた</p>");
    put(p, BUNDLED_SAMPLES_PATH, JSON.stringify([]));

    const states = classifyFiles(p, generated, null);

    expect(states[0]!.state).toBe("foreign");
    // 見本ではないので、言い方を変えない
    expect(states[0]!.wasSample).toBeUndefined();
  });

  it("一覧が無い案件では今までどおり", () => {
    // 古い案件・自分で作った案件を壊さない
    const states = classifyFiles(project(SAMPLE, false), generated, null);

    expect(states[0]!.state).toBe("foreign");
  });
});
