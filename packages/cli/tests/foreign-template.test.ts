import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";

import { afterEach, describe, expect, it } from "vitest";

import { foreignTemplateFiles } from "../src/deploy/plan.js";

/**
 * **別のテンプレートから来た生成物**を見つける（B-41 ⑥ / B-40 の機械検査）。
 *
 * ▷ **実際に在った**（B-40）: 実案件の `/about` `/service` が
 * **kit の見本（Green Leaf）のサンプル本文のまま**で、
 * **本番へ出た瞬間に別会社の紹介文が indexed される**ところだった。
 *
 * ▷ **人は気づけない。** ナビから辿れず、**sitemap にだけ載っていた**。
 * 見た目を見て回っても出てこない。**hash を突き合わせるしかない。**
 */
const roots: string[] = [];

function project(
  own: string | null,
  files: Record<string, string>,
): string {
  const root = mkdtempSync(join(tmpdir(), "agentcms-fp-"));
  roots.push(root);

  if (own !== null) {
    const m = join(root, ".agentcms", "manifest");
    mkdirSync(m, { recursive: true });
    writeFileSync(
      join(m, "template.json"),
      JSON.stringify({ fingerprint: { total: own } }),
    );
  }

  for (const [rel, body] of Object.entries(files)) {
    const p = join(root, rel);
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, body);
  }

  return root;
}

const stamp = (fp: string): string =>
  `{{-- generated by agentcms template apply — source: x.html (fingerprint ${fp}) — 手動編集すると再 apply 時に conflict になります --}}\n<p>本文</p>\n`;

afterEach(() => {
  for (const r of roots.splice(0)) rmSync(r, { recursive: true, force: true });
});

describe("別のテンプレートから来た生成物を見つける", () => {
  /** 🔴 **これが B-40 だった** */
  it("案件のものでない fingerprint を名指しする", () => {
    const root = project("be16b2716b23aaaa", {
      "resources/views/public/home.blade.php": stamp("be16b2716b23"),
      "resources/views/public/about.blade.php": stamp("2ec20387b570"),
    });

    const out = foreignTemplateFiles(root);

    expect(out).toHaveLength(1);
    expect(out[0]?.path).toContain("about.blade.php");
    expect(out[0]?.fingerprint).toBe("2ec20387b570");
  });

  it("全部この案件のものなら 0 件", () => {
    const root = project("be16b2716b23aaaa", {
      "resources/views/public/home.blade.php": stamp("be16b2716b23"),
      "modules/Contact/views/form.blade.php": stamp("be16b2716b23"),
    });

    expect(foreignTemplateFiles(root)).toStrictEqual([]);
  });

  /** **modules の下も見る**（取り込みは `modules/` にも書く） */
  it("modules の下も見る", () => {
    const root = project("be16b2716b23aaaa", {
      "modules/Contact/views/form.blade.php": stamp("2ec20387b570"),
    });

    expect(foreignTemplateFiles(root)).toHaveLength(1);
  });

  /** **生成物でないファイルは見ない**（手書きの view を巻き込まない） */
  it("署名の無いファイルは見ない", () => {
    const root = project("be16b2716b23aaaa", {
      "resources/views/public/hand.blade.php": "<p>手で書いた</p>\n",
    });

    expect(foreignTemplateFiles(root)).toStrictEqual([]);
  });

  // ── 逆向き: 騒ぎすぎない ──────────────────────────

  /** **取り込んでいない案件で騒がない**（記録が無ければ判定しない） */
  it("取り込みの記録が無ければ何も言わない", () => {
    const root = project(null, {
      "resources/views/public/about.blade.php": stamp("2ec20387b570"),
    });

    expect(foreignTemplateFiles(root)).toStrictEqual([]);
  });

  /** **記録が読めないときも黙る。**「読めなかった」を「食い違い」にしない */
  it("記録が壊れていても何も言わない", () => {
    const root = mkdtempSync(join(tmpdir(), "agentcms-fp-"));
    roots.push(root);
    const m = join(root, ".agentcms", "manifest");
    mkdirSync(m, { recursive: true });
    writeFileSync(join(m, "template.json"), "{ 壊れた JSON");
    const v = join(root, "resources", "views", "public");
    mkdirSync(v, { recursive: true });
    writeFileSync(join(v, "about.blade.php"), stamp("2ec20387b570"));

    expect(foreignTemplateFiles(root)).toStrictEqual([]);
  });

  it("view が 1 つも無くても落ちない", () => {
    expect(foreignTemplateFiles(project("be16b2716b23aaaa", {}))).toStrictEqual(
      [],
    );
  });
});
