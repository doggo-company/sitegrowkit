import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

import { afterAll, describe, expect, it } from "vitest";

import { generateFromPlan } from "../src/importer/generate.js";
import { buildImportedPage } from "../src/importer/imported-page.js";
import { buildPlan } from "../src/importer/plan.js";
import type { ContentSchema } from "../src/importer/plan-types.js";
import { analyzeTemplateDir } from "../src/inspect/analyze.js";

/**
 * 取り込んだ 1 枚を、画面から編集できるページの材料にする（R03 / B-42）。
 *
 * ここで固定するのは 6 つ:
 *   1. **生成（`generateFromPlan`）に繋がっている** — helper が試験からしか呼ばれない状態に戻らない
 *   2. **枠（layout）と中身（ブロック）を、生成後の Blade から起こす**（asset() を保つ）
 *   3. **元サイトの一部を消して公開しない** — 変換できないブロックが在ればページごと作らない（Codex ①）
 *   4. **中で意味が閉じている Blade は原本のまま置き、編集できないと明示する**
 *   5. **鍵と layout はページごとに隔離する**（`imported_home_*` / `layouts/preserved/home`）（Codex ②）
 *   6. **`@php` の中身を HTML として読まない**（枠に在っても原文のまま戻る）
 */
const cleanups: string[] = [];
afterAll(() => {
  for (const dir of cleanups) rmSync(dir, { recursive: true, force: true });
});

const BLADE = `{{-- generated by agentcms template apply (standalone/preserve mode) --}}
<!doctype html><html lang="ja"><head><meta charset="utf-8"><title>みどり造園</title><style>.hero{color:#0f4c46}</style></head><body class="home">
<div class="bg-pattern"></div>
<nav id="navbar"><img src="{{ asset('imported/images/logo.png') }}" alt="logo"><a href="#home">ホーム</a></nav>
<section id="home"><h1>庭をつくる</h1><p>庭づくりの会社です。</p></section>
<div class="fullbleed-band"></div>
<section id="news"><h2>NEWS</h2>
@foreach ($news as $item)
  <article><time>{{ $item->published_at?->format('Y.m.d') }}</time><a href="#">{{ $item->title }}</a></article>
@endforeach
</section>
<section class="conditional">@if (true)<p>重要な本文</p>@endif</section>
<section id="contact"><h2>CONTACT</h2><p>お気軽にご相談ください。</p></section>
<footer class="footer">@php $year = ['<span>2026</span>']; @endphp<small>&copy; {{ $year[0] }}</small></footer>
<script src="{{ asset('imported/js/a.js') }}"></script>
</body></html>`;

const build = (knownTypes: string[] = ["news", "works"], blade = BLADE) =>
  buildImportedPage({
    source: "index.html",
    blade,
    title: "ホーム",
    slug: "home",
    scope: "home",
    publish: true,
    front: true,
    knownTypes: new Set(knownTypes),
  });

const built = () => {
  const out = build();
  if (typeof out === "string") throw new Error(out);

  return out;
};

describe("buildImportedPage", () => {
  it("内部ページへの静的ルートも管理画面で編集できる行き先にする", () => {
    const result = buildImportedPage({
      source: "index.html",
      blade: `<html><head><title>見本</title></head><body><section><h1>見本</h1><a href="{{ route('company') }}#access">会社へ</a></section></body></html>`,
      title: "見本", slug: "home", scope: "home", publish: true, front: true,
      knownTypes: new Set(), routeUrls: new Map([["company", "/company"]]),
    });
    if (typeof result === "string") throw new Error(result);

    expect(result.page.blocks[0]?.props.link_1_href).toBe("/company#access");
    expect(result.page.blocks[0]?.props.link_1_text).toBe("会社へ");
  });

  // ── 2. 枠と中身を、生成後の Blade から起こす ─────────────

  it("原本の順で、静的な節・帯・一覧・素通しの部品が並ぶ（1 つも落とさない）", () => {
    const b = built();

    expect(b.page.blocks.map((x) => x.type)).toEqual([
      "imported_home_home",
      "imported_home_fullbleed_band",
      "imported_home_news",
      "imported_home_conditional",
      "imported_home_contact",
    ]);
    // 原本の文言が初期値に入る（運用者が最初に見るのは原本そのまま）
    expect(b.page.blocks[0]!.props).toEqual({
      heading_1: "庭をつくる",
      body_1: "庭づくりの会社です。",
    });
    // 一覧は binding ごと（無いと空で出る）
    expect(b.page.blocks[2]!.binding).toMatchObject({
      source: "collection",
      type: "news",
    });
    expect(b.page).toMatchObject({
      title: "ホーム",
      slug: "home",
      publish: true,
      front: true,
      source: "index.html",
    });
  });

  it("枠は layouts/preserved/<slug> に、asset() を保ったまま起こす", () => {
    const layout = built().files.find(
      (f) => f.target === "resources/views/layouts/preserved/home.blade.php",
    );

    expect(layout).toBeDefined();
    const content = String(layout!.content);
    expect(content).toContain(".hero{color:#0f4c46}");
    expect(content).toContain("{{ asset('imported/images/logo.png') }}");
    expect(content).toContain("{{ asset('imported/js/a.js') }}");
    expect(content).toContain("@yield('content')");
    // 中身は枠に残らない
    expect(content).not.toContain("庭をつくる");
    expect(content).not.toContain("CONTACT");
    // <html> / <body> の属性を落とさない
    expect(content).toContain('<html lang="ja">');
    expect(content).toContain('<body class="home">');
  });

  it("部品の view は原本の id を保つ（ナビのアンカーが死なない）", () => {
    const view = built().files.find(
      (f) =>
        f.target ===
        "resources/views/components/document/imported-home-contact.blade.php",
    );

    expect(view).toBeDefined();
    expect(String(view!.content)).toContain('<section id="contact">');
    expect(String(view!.content)).toContain("{{ $props['heading_1'] ?? '' }}");
  });

  // ── 6. @php を HTML として読まない ─────────────────────

  it("枠の中の @php は原文のまま戻る", () => {
    const layout = String(
      built().files.find((f) =>
        f.target.endsWith("layouts/preserved/home.blade.php"),
      )!.content,
    );

    // 文字列の中の <span> が要素として解釈されて形が変わっていない
    expect(layout).toContain("@php $year = ['<span>2026</span>']; @endphp");
    expect(layout).not.toContain("@agentcms-php-");
  });

  // ── 4. 中で意味が閉じている Blade は原本のまま置く ─────────

  it("@if (true) の節は、本文を保ったまま素通しの部品になり、編集できないと名乗る", () => {
    const b = built();

    // 🔴 Codex 再現: header / section.hero h1 / section.conditional @if(true)<p>重要な本文</p>@endif / footer
    //    で「skipped=conditional, blocks=1, publish=true」になっていた。元サイトの一部が消える
    expect(b.page.passthrough).toEqual(["section.conditional"]);

    const view = b.files.find((f) =>
      f.target.endsWith("imported-home-conditional.blade.php"),
    );
    expect(String(view!.content)).toContain(
      "@if (true)<p>重要な本文</p>@endif",
    );

    const def = JSON.parse(
      String(
        b.files.find((f) =>
          f.target.endsWith("imported_home_conditional.json"),
        )!.content,
      ),
    ) as { label: string; propsSchema: Record<string, unknown> };
    expect(def.label).toContain("画面からは編集できません");
    expect(def.propsSchema).toEqual({});
  });

  // ── 3. 変換できないブロックが在ればページごと作らない ─────

  it("外の変数を参照する Blade が在れば、ページごと作らず理由を返す（本文を消して公開しない）", () => {
    const out = build(
      ["news", "works"],
      BLADE.replace(
        '<section class="conditional">@if (true)<p>重要な本文</p>@endif</section>',
        '<section id="gallery">@if ($works->isEmpty())<p>準備中</p>@endif</section>',
      ),
    );

    expect(typeof out).toBe("string");
    expect(out).toContain("section#gallery");
    expect(out).toContain("$works");
    expect(out).toContain("ページは作りません");
    expect(out).toContain("何も消えません");
  });

  it("指令が無くても {{ $x }} で外の変数を参照する節が在れば、ページごと作らない", () => {
    const out = build(
      ["news", "works"],
      BLADE.replace(
        '<section class="conditional">@if (true)<p>重要な本文</p>@endif</section>',
        '<section id="count"><p>{{ $works->count() }} 件</p></section>',
      ),
    );

    expect(typeof out).toBe("string");
    expect(out).toContain("section#count");
    expect(out).toContain("$works");
  });

  it("一覧の元の型がこの案件に無ければ、ページごと作らず理由を返す", () => {
    const out = build(["works"]);

    expect(typeof out).toBe("string");
    expect(out).toContain("section#news");
    expect(out).toContain("[news]");
  });

  it("body 直下に <section> が無ければ、理由を返して作らない", () => {
    const out = build(
      [],
      `<html><head><title>x</title></head><body><nav>a</nav><div class="x">b</div><footer>c</footer></body></html>`,
    );

    expect(typeof out).toBe("string");
    expect(out).toContain("index.html");
    expect(out).toContain("<section>");
  });

  it("<head> が読めなければ、理由を返して作らない", () => {
    const out = build([], `<section id="a"><h1>a</h1></section>`);

    expect(typeof out).toBe("string");
    expect(out).toContain("layout");
  });

  // ── 5. 鍵と layout はページごとに隔離する ────────────────

  it("鍵にも layout にもページの名前が付く（別ページと 1 ファイルも衝突しない）", () => {
    const home = built();
    const company = buildImportedPage({
      source: "company.html",
      blade: BLADE,
      title: "会社概要",
      slug: "company",
      scope: "company",
      publish: false,
      front: false,
      knownTypes: new Set(["news", "works"]),
    });
    if (typeof company === "string") throw new Error(company);

    const homeTargets = home.files.map((f) => f.target);
    const companyTargets = company.files.map((f) => f.target);

    // 🔴 Codex 再現: scope=home と other で両方 `layouts/preserved.blade.php` を生成していた。
    //    layout もページごとに 1 本（`DocumentPageView` が slug で引く）
    expect(homeTargets).toContain(
      "resources/views/layouts/preserved/home.blade.php",
    );
    expect(companyTargets).toContain(
      "resources/views/layouts/preserved/company.blade.php",
    );

    for (const t of homeTargets) expect(companyTargets).not.toContain(t);
  });
});

/**
 * **helper ではなく、生成の本体に繋がっていること**を固定する。
 *
 * 前の版では `buildImportedPageBlocks()` と `buildImportedLayout()` が試験からしか
 * 呼ばれておらず、利用者の実経路（inspect → plan → apply）では 1 ファイルも書かれなかった。
 */
describe("generateFromPlan がページの材料を返す（standalone モード）", () => {
  const dir = mkdtempSync(join(tmpdir(), "agentcms-imported-page-"));
  cleanups.push(dir);
  mkdirSync(join(dir, "images"));
  writeFileSync(join(dir, "images", "logo.png"), "png");
  writeFileSync(
    join(dir, "index.html"),
    `<!doctype html><html lang="ja"><head><meta charset="utf-8"><title>みどり造園</title><style>.hero{color:red}</style></head><body>
<div class="bg-pattern"></div>
<nav id="navbar"><img src="images/logo.png" alt="logo"><ul><li><a href="#home">ホーム</a></li><li><a href="#contact">お問い合わせ</a></li></ul></nav>
<section id="home"><h1>庭をつくる</h1><p>庭づくりの会社です。</p></section>
<div class="fullbleed-band"></div>
<section id="contact"><h2>CONTACT</h2><p>お気軽にご相談ください。</p></section>
<footer class="footer"><small>&copy; みどり造園</small></footer>
<script>document.body.classList.add("ready")</script>
</body></html>`,
  );

  const manifest = analyzeTemplateDir(dir, "probe");
  const plan = buildPlan(manifest, {});

  it("この fixture は standalone（前提）", () => {
    expect(plan.layout.header_selector).toBeNull();
    expect(plan.pages.find((p) => p.source === plan.entry)?.url).toBe("/");
  });

  it("トップの原本 1 枚を、公開するページ（front）として返す", () => {
    const result = generateFromPlan(dir, manifest, plan);

    expect(result.importedPageNotes).toEqual([]);
    expect(result.importedPages).toHaveLength(1);

    const page = result.importedPages[0]!;
    expect(page).toMatchObject({
      slug: "home",
      front: true,
      publish: true,
      source: "index.html",
    });
    expect(page.blocks.map((b) => b.type)).toEqual([
      "imported_home_home",
      "imported_home_fullbleed_band",
      "imported_home_contact",
    ]);
    expect(page.passthrough).toEqual([]);
  });

  it("部品と layout を files に含め、静的なトップの Blade も残す", () => {
    const targets = generateFromPlan(dir, manifest, plan).files.map(
      (f) => f.target,
    );

    expect(targets).toContain(
      "resources/views/layouts/preserved/home.blade.php",
    );
    expect(targets).toContain("content/components/imported_home_home.json");
    expect(targets).toContain(
      "resources/views/components/document/imported-home-home.blade.php",
    );
    // front_page_id が外れたときの受け皿。無いとトップが消える
    expect(targets).toContain("resources/views/public/home.blade.php");
  });

  it("layout は生成後の Blade から起こす（asset() 化された参照を持つ）", () => {
    const layout = generateFromPlan(dir, manifest, plan).files.find((f) =>
      f.target.endsWith("layouts/preserved/home.blade.php"),
    )!;

    expect(String(layout.content)).toContain(
      "{{ asset('imported/images/logo.png') }}",
    );
    expect(String(layout.content)).not.toContain('src="images/logo.png"');
  });

  it("knownTypes を渡せば、その型で一覧の可否を判断する", () => {
    // この fixture に一覧は無いので、型の集合を変えても結果は同じ（渡し口が生きていることだけ見る）
    const result = generateFromPlan(dir, manifest, plan, {
      knownTypes: new Set(),
    });

    expect(result.importedPages).toHaveLength(1);
  });
});

describe("generateFromPlan はトップ以外の standalone ページもページにする（R03 続き (1)）", () => {
  const dir = mkdtempSync(join(tmpdir(), "agentcms-imported-pages-"));
  cleanups.push(dir);
  mkdirSync(join(dir, "images"));
  writeFileSync(join(dir, "images", "logo.png"), "png");
  const shell = (title: string, body: string) =>
    `<!doctype html><html lang="ja"><head><meta charset="utf-8"><title>${title}</title><style>.x{color:red}</style></head><body>
<nav id="navbar"><img src="images/logo.png" alt="logo"><a href="index.html">ホーム</a><a href="company.html">会社</a></nav>
${body}
<footer class="footer"><small>&copy;</small></footer>
</body></html>`;
  writeFileSync(
    join(dir, "index.html"),
    shell("トップ", `<section id="home"><h1>庭をつくる</h1><p>本文。</p></section>`),
  );
  writeFileSync(
    join(dir, "company.html"),
    shell(
      "会社概要",
      `<main class="sub"><section id="about"><h1>会社概要</h1><p>所在地。</p><img src="images/logo.png" alt="ロゴ"><a href="#top">上へ</a></section></main>`,
    ),
  );

  const manifest = analyzeTemplateDir(dir, "probe", { entry: "index.html" });
  const plan = buildPlan(manifest, {});
  const result = generateFromPlan(dir, manifest, plan);

  it("standalone で、トップと会社概要の 2 枚がページの材料になる", () => {
    expect(plan.layout.header_selector).toBeNull();
    expect(result.importedPageNotes, result.importedPageNotes.join("\n")).toEqual([]);
    expect(result.importedPages.map((p) => [p.slug, p.front, p.layout])).toEqual([
      ["home", true, "layouts.preserved.home"],
      ["company", false, "layouts.preserved.company"],
    ]);
  });

  it("会社概要は main の中身を割り、画像とリンクも項目になる", () => {
    const company = result.importedPages.find((p) => p.slug === "company")!;

    expect(company.blocks.map((b) => b.type)).toEqual(["imported_company_about"]);
    expect(Object.keys(company.blocks[0]!.props).sort()).toEqual([
      "body_1",
      "heading_1",
      "image_1_alt",
      "image_1_src",
      "link_1_href",
      "link_1_text",
    ]);
    expect(company.blocks[0]!.props["image_1_src"]).toBe("/imported/images/logo.png");

    const layout = String(
      result.files.find((f) => f.target === "resources/views/layouts/preserved/company.blade.php")!
        .content,
    );
    expect(layout).toContain('<main class="sub">');
    expect(layout).toContain("@yield('content')");
    expect(layout).toContain('<nav id="navbar">');
  });

  it("routes/imported.php は Route::view ではなく、ページを先に見る controller を通す", () => {
    const routes = String(
      result.files.find((f) => f.target === "routes/imported.php")!.content,
    );

    expect(routes).not.toContain("Route::view(");
    expect(routes).toContain(
      "ImportedPageController::class)->defaults('view', 'pages.company')->defaults('layout', 'layouts.preserved.company')",
    );
  });

  it("部品の定義では、画像の場所とリンクの行き先が url 型になる（kit の検証に任せる）", () => {
    const def = JSON.parse(
      String(
        result.files.find((f) => f.target === "content/components/imported_company_about.json")!
          .content,
      ),
    ) as { propsSchema: Record<string, { type: string }> };

    expect(def.propsSchema["image_1_src"]!.type).toBe("url");
    expect(def.propsSchema["link_1_href"]!.type).toBe("url");
    expect(def.propsSchema["heading_1"]!.type).toBe("string");
  });
});

describe("generateFromPlan は、作れない理由を黙らない", () => {
  const FIXTURE = resolve(__dirname, "../../../examples/html-template");
  const SCHEMAS = resolve(__dirname, "../../../template/content/schemas");
  const loadSchema = (id: string): ContentSchema =>
    JSON.parse(
      readFileSync(join(SCHEMAS, `${id}.json`), "utf8"),
    ) as ContentSchema;
  const manifest = analyzeTemplateDir(FIXTURE, "fixture");
  const plan = buildPlan(manifest, {
    works: loadSchema("works"),
    news: loadSchema("news"),
    contact: loadSchema("contact"),
  });

  it("layout モード（header を抽出できた案件）では作らず、理由を返す", () => {
    expect(plan.layout.header_selector).not.toBeNull();

    const result = generateFromPlan(FIXTURE, manifest, plan);

    expect(result.importedPages).toEqual([]);
    expect(result.importedPageNotes.join("\n")).toContain("layout モード");
  });

  it("standalone にすれば、同梱見本も body > main の中身でページになる（トップが先）", () => {
    const standalone = {
      ...plan,
      layout: { ...plan.layout, header_selector: null, footer_selector: null },
    };
    const result = generateFromPlan(FIXTURE, manifest, standalone);
    const slugs = result.importedPages.map((p) => p.slug);

    // 同梱見本は body 直下に <section> を持たないが、<main> の中に中身が在る（R03 続き (3)）
    expect(slugs[0]).toBe("home");
    expect(slugs).toEqual(expect.arrayContaining(["home", "about", "service"]));
    expect(result.importedPages.find((p) => p.slug === "home")!.front).toBe(true);
    expect(result.importedPages.filter((p) => p.front)).toHaveLength(1);
    for (const slug of slugs) {
      expect(result.files.map((f) => f.target)).toContain(
        `resources/views/layouts/preserved/${slug}.blade.php`,
      );
    }
  });

  it("body 直下に <section> も <main> も無い原本は、そのページだけ作らず理由を返す", () => {
    const out = buildImportedPage({
      source: "plain.html",
      blade: `<html><head><title>x</title></head><body><header>h</header><div class="x"><p>b</p></div><footer>c</footer></body></html>`,
      title: "x",
      slug: "plain",
      scope: "plain",
      publish: true,
      front: false,
      knownTypes: new Set(),
    });

    expect(typeof out).toBe("string");
    expect(out).toContain("plain.html");
  });
});
